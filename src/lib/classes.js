export const ORDEM_CLASSES = ["Amigo","Companheiro","Pesquisador","Pioneiro","Excursionista","Guia"]

export function totalRequisitos(classeNome) {
  return CLASSES[classeNome]?.secoes.reduce((acc, s) => acc + s.requisitos.length, 0) || 0
}

export function calcularPct(progresso, classeNome) {
  const total = totalRequisitos(classeNome)
  if (!total) return 0
  const done = Object.values(progresso || {}).filter(Boolean).length
  return Math.round(done / total * 100)
}

export function getAvatarUrl(nome, seed) {
  const s = seed || nome?.replace(/\s+/g, '') || 'luminar'
  return `https://api.dicebear.com/7.x/avataaars/svg?seed=${s}&backgroundColor=1a2a8e&radius=50`
}
